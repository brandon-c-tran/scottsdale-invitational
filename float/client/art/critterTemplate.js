/* A baked critter as the animation runtime sees it: the skeleton, what the
   animation reads of the sculpt (arms, head, mouth, eyes), where its
   accessories sit (critterMeta.js, generated by the bake), and the file its
   mesh comes from. The mesh itself loads separately (critterAsset.js) and
   binds to the skeleton when it arrives. */
import * as THREE from "three";
import { CRITTER_META, CRITTER_BONES } from "./critterMeta.js";

const V = a => new THREE.Vector3(a[0], a[1], a[2]);

/* the species baked so far (each has at least its race file) */
export const BAKED_SPECIES = Object.freeze(Object.keys(CRITTER_META).filter(id => CRITTER_META[id]?.files?.race));

export function hasBaked(id) { return BAKED_SPECIES.includes(id); }

/* the file for a detail (hero falls back to race until it is baked) */
export function bakedFile(id, detail) {
  const files = CRITTER_META[id]?.files || {};
  const d = files[detail] ? detail : "race";
  return { detail: d, file: files[d]?.file || null, key: `${id}:${d}` };
}

export function bakedTemplate(id, detail = "race") {
  const meta = CRITTER_META[id];
  if (!meta) throw new Error(`float art: ${id} is not baked`);
  const info = { ...meta.info };
  for (const s of ["L", "R"]) {
    const a = meta.info[`arm${s}`];
    info[`arm${s}`] = { dir: V(a.dir), pole: V(a.pole), a: a.a, b: a.b, shoulder: V(a.shoulder) };
  }
  info.mouth = { p: V(meta.info.mouth.p) };
  info.eyes = (meta.info.eyes || []).map(e => ({ c: V(e.c), n: V(e.n), p: V(e.p) }));
  const hat = meta.sockets.hat;
  const { detail: d, file, key } = bakedFile(id, detail);
  return {
    version: 2, id, detail: d, file, key,
    bones: CRITTER_BONES.map(([name, parent], i) => ({ name, parent, at: V(meta.bones.slice(i * 3, i * 3 + 3)) })),
    info,
    sockets: { hat: { at: V(hat.at), s: hat.s, tilt: hat.tilt, halfW: hat.halfW }, shades: meta.sockets.shades },
    anchors: meta.anchors,
    fur: meta.fur,
    bounds: meta.bounds,
    geos: {},
    dispose() {},
  };
}

/* the fur's shells over a critter mesh: the same vertex buffers, only the
   furry triangles, drawn once per shell (cached on the geometry) */
export function shellGeometry(geo, shells) {
  const key = `shells:${shells}`;
  if (geo.userData[key]) return geo.userData[key];
  const fur = geo.userData.furIndex;
  if (!fur) return null;
  const g = new THREE.InstancedBufferGeometry();
  for (const name of ["position", "normal", "aColor", "aMat", "skinIndex", "skinWeight"]) g.setAttribute(name, geo.attributes[name]);
  g.setIndex(new THREE.BufferAttribute(fur, 1));
  g.instanceCount = shells;
  g.boundingBox = geo.boundingBox?.clone() || null;
  g.boundingSphere = geo.boundingSphere?.clone() || null;
  geo.userData[key] = g;
  return g;
}
